export type IconName = keyof typeof PATHS;

type IconProps = Omit<SVGProps<SVGSVGElement>, "name"> & {
  name: IconName;
  size?: number;
  /** Render filled instead of stroked (used for stars). */
  filled?: boolean;
  /** Accessible label; omit for decorative icons. */
  label?: string;
};

export function Icon({ name, size = 20, filled, label, strokeWidth = 1.8, ...rest }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? "currentColor" : "none"}
      stroke={filled ? "none" : "currentColor"}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      focusable="false"
      {...rest}
    >
      {PATHS[name]}
    </svg>
  );
}

/** The trailing arrow used on buttons and row links; nudges right on hover via `.v-arrow`. */
export function Arrow({ size = 18, className = "", ...rest }: { size?: number; className?: string } & Omit<SVGProps<SVGSVGElement>, "name">) {
  return <Icon name="arrow" size={size} strokeWidth={2} className={`v-arrow ${className}`.trim()} {...rest} />;
}
